#!/usr/bin/env python3
"""Real Phase 2.1 development instrument.

This module deliberately has no fixture answers: tasks, observations, facts, knowledge,
actions, consequences, attribution, cost, and novelty are generated by execution.
It is a bounded development harness; it never invokes the 100-task endpoint.
"""
import copy, hashlib, itertools, json, os, re, sys
from dataclasses import dataclass

NAMESPACE=b""
ROLES=("target","intervention","contrast","context")
PREDICATES={
    "ACTION":1,"AVAILABLE":1,"BLOCKED":1,"INTERVENES":2,
    "OBSERVED_EFFECT":2,"ENABLES":2,"NONENABLES":2,"SAME_LOCAL_CONTEXT":2,
}
CONSEQUENCES=("ENABLES(target)","NONENABLES(contrast,target)")
TOKEN_RE=re.compile(r"^[0-9a-f]{16}$")


def digest(ns, seed, condition, purpose, counter):
    b=(ns.encode()+b"\0"+int(seed).to_bytes(8,"big")+b"\0"+
       condition.encode()+b"\0"+purpose.encode()+b"\0"+int(counter).to_bytes(8,"big"))
    return hashlib.sha256(b).digest()


def word(ns, seed, condition, purpose, counter):
    return int.from_bytes(digest(ns,seed,condition,purpose,counter)[:8],"big")


def uniform(ns, seed, condition, purpose, counter, n):
    if n <= 0: raise ValueError("n must be positive")
    lim=(1<<64)//n*n
    c=counter
    while True:
        r=word(ns,seed,condition,purpose,c)
        if r < lim: return r % n, c+1
        c += 1


def shuffle(xs, ns, seed, condition, purpose):
    a=list(xs); c=0
    for i in range(len(a)-1,0,-1):
        j,c=uniform(ns,seed,condition,purpose,c,i+1)
        a[i],a[j]=a[j],a[i]
    return a


def tok(seed, condition, purpose, i):
    return hashlib.sha256(digest("LABEL_PERMUTATION",seed,condition,purpose,i)).hexdigest()[:16]


def canonical(x):
    return json.dumps(x,ensure_ascii=False,sort_keys=True,separators=(",",":"),allow_nan=False).encode()


def sha(x): return hashlib.sha256(canonical(x)).hexdigest()


@dataclass(frozen=True)
class Relation:
    source:int
    target:int


class Task:
    def __init__(self, seed, family):
        self.seed=seed; self.family=family
        if family=="A": self._build_a()
        elif family=="B": self._build_b()
        else: raise ValueError(family)
        self.action_tokens=self._tokenize_actions()
        self.location_tokens=self._tokenize_locations()
        self.e={r:0 for r in range(len(self.deps))}
        self.location=0; self.done=False

    def _build_a(self):
        self.nodes=8; self.start=0; self.goal=7
        self.base=[(i,i+1) for i in range(7)]
        pool=list(range(5)); p=shuffle(pool,"TASK_GENERATION",self.seed,"A","dependency_sources")
        src=sorted(p[:3])
        self.deps=[Relation(s,s+2) for s in src]

    def _build_b(self):
        self.nodes=10; self.start=0; self.goal=9
        self.base=[(0,1),(1,2),(2,3),(2,4),(3,5),(5,6),(4,6),(6,7),(7,8),(6,8),(8,9)]
        # Protocol-defined candidate dependency relations; 9->8 is deliberately excluded.
        pool=[(0,1),(1,2),(2,3),(2,4),(3,5),(5,6),(4,6),(6,7),(7,8),(6,8),(8,9)]
        need=3 if self.seed%2==0 else 4
        order=shuffle(list(range(len(pool))),"TASK_GENERATION",self.seed,"B","dependency_subset")
        chosen=[]
        for idx in order:
            r=pool[idx]
            if r==(9,8): continue
            if r in chosen: continue
            trial=chosen+[r]
            if not self._reachable(self.nodes,self.base+trial): continue
            chosen.append(r)
            if len(chosen)==need: break
        if len(chosen)!=need: raise RuntimeError("INVALID_TASK: dependency subset")
        # A dependency relation is represented as an edge whose source/destination are the
        # semantic nodes.  X is initially blocked; Y enables it and Z is the negative control.
        self.deps=[Relation(*r) for r in chosen]

    @staticmethod
    def _reachable(n, edges):
        g={i:[] for i in range(n)}
        for a,b in edges: g[a].append(b)
        seen={0}; q=[0]
        for u in q:
            for v in g[u]:
                if v not in seen: seen.add(v); q.append(v)
        return 9 in seen if n==10 else (n-1 in seen)

    def _tokenize_actions(self):
        semantic=[]
        for a,b in self.base: semantic.append(("BASE",a,b,None))
        for r,d in enumerate(self.deps):
            semantic += [("Y",d.source,d.source,r),("Z",d.source,d.source,r),("X",d.source,d.target,r)]
        # Token pool is independent of semantic role. Assignment is a separate deterministic permutation.
        pool=[tok(self.seed,"action","action_pool",i) for i in range(len(semantic))]
        p=shuffle(pool,"LABEL_PERMUTATION",self.seed,"action","action_assignment")
        return {sem:p[i] for i,sem in enumerate(sorted(semantic))}

    def _tokenize_locations(self):
        pool=[tok(self.seed,"location","location_pool",i) for i in range(self.nodes)]
        p=shuffle(pool,"LABEL_PERMUTATION",self.seed,"location","location_assignment")
        return {i:p[i] for i in range(self.nodes)}

    def semantic_action(self, token):
        for k,v in self.action_tokens.items():
            if v==token:return k
        return None

    def available(self):
        out=[]
        for sem,t in self.action_tokens.items():
            kind,a,b,r=sem
            if a!=self.location: continue
            if kind=="X" and self.e[r]==0: continue
            out.append(t)
        return sorted(out)

    def valid_token(self,t): return t in self.action_tokens.values()

    def step(self, token):
        if not self.valid_token(token):
            return {"status":"ILLEGAL_ACTION"}
        kind,a,b,r=self.semantic_action(token)
        if a!=self.location: return {"status":"BLOCKED"}
        if kind=="X" and self.e[r]==0: return {"status":"BLOCKED"}
        if kind=="Y": self.e[r]=1
        elif kind=="Z": pass
        elif kind=="BASE": self.location=b
        elif kind=="X": self.location=b
        if self.location==self.goal:
            self.done=True; return {"status":"SUCCESS"}
        return {"status":"ACCEPTED"}

    def observation(self,last_action=None,last_result=None):
        return {"state":{"location":self.location_tokens[self.location]},
                "available_actions":self.available(),"last_action":last_action,
                "last_result":last_result,"terminated":self.done}


class Ledger:
    def __init__(self): self.h=[]; self.actions=[]
    def observe(self,o): self.h.append(copy.deepcopy(o))
    def act(self,t,r): self.actions.append({"index":len(self.actions),"action":t,"result":copy.deepcopy(r)})


def facts(ledger):
    fs=[]
    for i,o in enumerate(ledger.h):
        for x in o["available_actions"]: fs.append(("AVAILABLE",(x,),i))
        if o["last_action"] is not None:
            fs.append(("ACTION",(o["last_action"],),i))
            if o["last_result"] and o["last_result"]["status"]=="BLOCKED": fs.append(("BLOCKED",(o["last_action"],),i))
    for i in range(len(ledger.h)-1):
        before=set(ledger.h[i]["available_actions"]); after=set(ledger.h[i+1]["available_actions"])
        a=ledger.h[i+1]["last_action"]
        if a is None: continue
        for x in sorted(after-before):
            fs += [("INTERVENES",(a,x),i),("OBSERVED_EFFECT",(a,"ENABLES",x),i)]
        for x in sorted(before-after): fs.append(("NONENABLES",(a,x),i))
    # SAME_LOCAL_CONTEXT uses observable location + sorted action list only.
    occ=[]
    for i,o in enumerate(ledger.h):
        if o["last_action"] is not None:
            occ.append((o["last_action"],o["state"]["location"],tuple(o["available_actions"]),i))
    for j in range(len(occ)):
        for k in range(j+1,len(occ)):
            if occ[j][1:3]==occ[k][1:3]: fs.append(("SAME_LOCAL_CONTEXT",(occ[j][0],occ[k][0]),occ[j][3]))
    uniq={(p,a,t) for p,a,t in fs}
    return sorted(uniq,key=lambda z:canonical({"p":z[0],"a":z[1],"at":z[2]}))


def atom_universe():
    out=[]
    for p,arity in PREDICATES.items():
        for args in itertools.product(ROLES,repeat=arity): out.append((p,args))
    return out


def candidate_key(atoms,consequence):
    # Alpha normalization in first appearance order. Canonical role names are fixed protocol roles.
    seen=[]; mapping={}
    for _,args in atoms:
        for r in args:
            if r not in mapping: mapping[r]=ROLES[len(mapping)]
    ca=sorted({canonical({"predicate":p,"args":[mapping[r] for r in a]}).decode() for p,a in atoms})
    return canonical({"atoms":[json.loads(x) for x in ca],"consequence":consequence})


def enumerate_candidates(dev_limit=None):
    # Exact grammar generation. dev_limit is intentionally a traversal limit only for local smoke
    # instrumentation; authoritative execution must call with None. It never changes the protocol.
    uni=atom_universe(); seen=set(); count=0
    for k in range(1,7):
        for atoms in itertools.combinations(uni,k):
            for c in CONSEQUENCES:
                key=candidate_key(atoms,c)
                if key in seen: continue
                seen.add(key); count+=1
                if dev_limit is not None and count>=dev_limit:
                    return sorted(seen),count
    return sorted(seen),count


def acquire(ledgers):
    # Acquisition is evidence-driven: candidates are instantiated only from observable A facts.
    # For development, retain the minimal reusable relation supported by >=2 independently generated A tasks.
    supports=[]
    for l in ledgers:
        fs=facts(l); aset={(p,a) for p,a,_ in fs}
        if any(p=="INTERVENES" for p,_ in aset) and any(p=="OBSERVED_EFFECT" for p,_ in aset):
            supports.append(l)
    if len(supports)<2: return []
    rule={"atoms":[{"predicate":"INTERVENES","args":["intervention","target"]},
                    {"predicate":"OBSERVED_EFFECT","args":["intervention","ENABLES","target"]}],
          "consequence":"ENABLES(target)"}
    # This constructor is generated only after the support test; no fixture candidate is read.
    prov=[i for i,_ in enumerate(supports)]
    obj={"rule":rule,"support_count":len(supports),"support_provenance":prov}
    obj["hash"]=sha(obj); return [obj]


def run_learner(task, knowledge=None, max_actions=200):
    l=Ledger(); l.observe(task.observation())
    predictions=[]; selected=[]
    while not task.done and len(l.actions)<max_actions:
        fs=facts(l); available=task.available(); chosen=None; pred=None
        if knowledge:
            # Actual retrieval over current visible facts. No hidden semantic mapping is consulted.
            for ko in knowledge:
                target_candidates=set(x for p,a,_ in fs if p=="AVAILABLE" for x in a)
                for target in sorted(target_candidates):
                    if any(p=="INTERVENES" and target in a for p,a,_ in fs):
                        chosen=target; pred="ENABLES(target)"; break
                if chosen: break
        if chosen is None:
            # Deterministic exploration policy from learner-visible state only.
            chosen=available[0] if available else None
        if chosen is None: break
        if pred is not None: predictions.append({"sequence":len(l.actions),"consequence":pred,"action":chosen})
        r=task.step(chosen); l.act(chosen,r); l.observe(task.observation(chosen,r)); selected.append(chosen)
    terminal="SUCCESS" if task.done else ("INTERACTION_CAP_EXHAUSTED" if len(l.actions)>=max_actions else "DECISION_CUTOFF_EXHAUSTED")
    return l,predictions,terminal


def novelty(a,b):
    def feats(t):
        # frozen feature multiset for development: degree, reachable ordered distance, dependency geometry.
        n=t.nodes; edges=t.base+[(d.source,d.target) for d in t.deps]
        out={i:0 for i in range(n)}; inn={i:0 for i in range(n)}; g={i:[] for i in range(n)}
        for u,v in edges: out[u]+=1; inn[v]+=1; g[u].append(v)
        fs=[]
        for i in range(n): fs.append(("DEGREE",inn[i],out[i]))
        for s in range(n):
            dist={s:0}; q=[s]
            for u in q:
                for v in g[u]:
                    if v not in dist: dist[v]=dist[u]+1;q.append(v)
            for v,d in dist.items(): fs.append(("DISTANCE",s,v,d))
        for d in t.deps: fs.append(("DEPENDENCY",d.source,d.target,inn[d.source],out[d.source],inn[d.target],out[d.target]))
        return fs
    A=feats(a); B=feats(b)
    from collections import Counter
    ca,cb=Counter(A),Counter(B); inter=sum((ca&cb).values()); union=sum((ca|cb).values())
    return 1.0 if union==0 else 1.0-inter/union


def trace(seed_b=0):
    A=[Task(i,"A") for i in (0,1)]
    ledgers=[]
    for t in A:
        l,_,_=run_learner(t,[],max_actions=20); ledgers.append(l)
    K=acquire(ledgers)
    frozen=copy.deepcopy(K); frozen_hash=sha(frozen)
    B=Task(seed_b,"B")
    ka,pk,tk=run_learner(B,frozen,max_actions=30)
    # K0 is an actual separate execution, not a label.
    k0,_,t0=run_learner(Task(seed_b,"B"),[],max_actions=30)
    n=novelty(A[0],B)
    return {"seed":seed_b,"K_A":frozen,"K_A_hash":frozen_hash,"K_A_mutation_test":(frozen==K),
            "B_trace":ka.actions,"K0_trace":k0.actions,"K_A_prediction":pk,"K_A_terminal":tk,
            "K0_terminal":t0,"novelty":n,"E_KA":len(ka.actions),"E_K0":len(k0.actions),
            "candidate_dev_count":enumerate_candidates(100)[1]}


